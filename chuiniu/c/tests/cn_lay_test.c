static CnObj OBJS[CN_LAY_MAX_OBJS];

static void test_objects(void)
{
    TEST("the bodies are the study's: every die, every cup, in order");
    const int n = (int)(sizeof GOLD / sizeof GOLD[0]);
    int di = 0, ci = 0;
    const int nd = (int)(sizeof GOLD_DICE / sizeof GOLD_DICE[0]), nc = (int)(sizeof GOLD_CUPS / sizeof GOLD_CUPS[0]);
    for (int i = 0; i < n; i++) {
        const Gold *g = &GOLD[i];
        CnLayIn in = input(g->W, g->H, g->n, g->mine, 0);
        CnLay L;
        cn_lay_make(&in, &L);
        int k = cn_lay_objects(&in, &L, OBJS, CN_LAY_MAX_OBJS);
        int dice = 0, cups = 0;
        for (int o = 0; o < k; o++) {
            const CnObj *b = &OBJS[o];
            if (b->kind == CN_OBJ_DIE) {
                dice++;
                if (di >= nd || GOLD_DICE[di].c != i) { CHECK(0, "case %d: a die the study does not have", i); continue; }
                const GoldDie *d = &GOLD_DICE[di++];
                CHECK(b->seat == d->seat && near(b->x, d->x, EPS) && near(b->y, d->y, EPS) && near(b->yaw, d->yaw, 1e-4) && near(b->d, d->d, EPS),
                      "%dx%d n %d: seat %d's die at (%.4f, %.4f) turned %.4f, the study (%.4f, %.4f) %.4f", g->W, g->H, g->n, d->seat, b->x, b->y, b->yaw, d->x, d->y, d->yaw);
                CHECK(b->lift == b->d / 2, "a die rests on the table");
            } else {
                cups++;
                if (ci >= nc || GOLD_CUPS[ci].c != i) { CHECK(0, "case %d: a cup the study does not have", i); continue; }
                const GoldCup *u = &GOLD_CUPS[ci++];
                CHECK(b->seat == u->seat && near(b->R, u->R, EPS) && b->out == u->out, "%dx%d n %d: seat %d's cup", g->W, g->H, g->n, u->seat);
                if (!u->out) {
                    CHECK(near(b->x, u->x, EPS) && near(b->y, u->y, EPS) && b->lift == 0, "%dx%d n %d: seat %d's cup stands at (%.4f, %.4f)", g->W, g->H, g->n, u->seat, b->x, b->y);
                } else {
                    /* the lying cup is the study's, its lie made exact (cn_geom.c): its footprint's centre and its
                     * turn agree with the study's, its mouth sits a third of a point lower */
                    float occ[5];
                    cn_geom_occluder(b, 0, occ);
                    CHECK(near(occ[0], u->x + u->sh[1], EPS) && near(occ[1], u->y + u->sh[2], EPS) && near(occ[2], u->sh[0], EPS), "%dx%d n %d: the lying cup's footprint (%.4f, %.4f), the study (%.4f, %.4f)", g->W, g->H, g->n, occ[0], occ[1], u->x + u->sh[1], u->y + u->sh[2]);
                    double dr = 0;
                    for (int r = 0; r < 9; r++) dr = fmax(dr, fabs(b->rot[r] - u->rot[r]));
                    CHECK(dr < .01, "%dx%d n %d: the lying cup's turn within %.4f of the study's", g->W, g->H, g->n, dr);
                    const double ca = CN_CUP_TALL / sqrt(CN_CUP_TALL * CN_CUP_TALL + (1 - CN_CUP_RC) * (1 - CN_CUP_RC));
                    CHECK(near(b->lift, u->R * ca, 1e-3) && u->lift - b->lift > .2, "%dx%d n %d: lowered %.3f onto the table", g->W, g->H, g->n, u->lift - b->lift);
                }
            }
        }
        CHECK(OBJS[k - 1].mine && OBJS[k - 1].kind == CN_OBJ_CUP && OBJS[k - 1].tilt_angle == L.peek.angle, "my cup last, tipped by the peek");
        (void)dice; (void)cups;
    }
    CHECK(di == nd && ci == nc, "every die and cup of the study's met (%d of %d, %d of %d)", di, nd, ci, nc);
    /* my dice carry my faces */
    CnLayIn in = input(390, 718, 3, 1, 0);
    CnLay L; cn_lay_make(&in, &L);
    int k = cn_lay_objects(&in, &L, OBJS, CN_LAY_MAX_OBJS), f = 0;
    for (int o = 0; o < k; o++) if (OBJS[o].kind == CN_OBJ_DIE && OBJS[o].mine) { CHECK(OBJS[o].value == in.my_faces[f] && OBJS[o].cells[cn_die_slot(2, 1)] == in.my_faces[f], "my die %d shows %d", f, in.my_faces[f]); f++; }
    CHECK(f == 5, "five of mine");
    CHECK(cn_lay_objects(&in, &L, OBJS, 3) == -1, "a short array is refused, not overrun");
}

