static int near(double a, double b, double eps) { return fabs(a - b) <= eps; }
#define EPS .01

/* the study's table: Alex, Bo, Cy, Dee, Eve, Fay holding 5 4 5 3 5 2; at six seats Fay is out */
static CnLayIn input(int W, int H, int n, int mine, int me)
{
    static const uint8_t COUNTS[6] = { 5, 4, 5, 3, 5, 2 }, MINE[5] = { 1, 1, 3, 5, 6 };
    CnLayIn in;
    memset(&in, 0, sizeof in);
    in.seats = (uint8_t)n; in.me = (uint8_t)me; in.turn = (uint8_t)(mine ? me : (me + 1) % n);
    for (int v = 0; v < n && v < CN_LAY_SEATS; v++) in.dice[(me + v) % n] = COUNTS[v];   /* seven seats: the refusal test */
    in.out_mask = (uint8_t)(n == 6 ? 1 << ((me + 5) % n) : 0);
    memcpy(in.my_faces, MINE, 5);
    in.w = (float)W; in.h = (float)H; in.peek = 1; in.seed = 7;
    return in;
}

