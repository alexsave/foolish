// wiregen.c - prints web/src/gen/wire.ts: the TypeScript decoder of the binary surface, from
// the compiler's own offsetof and sizeof (src/wire_table.h). The web never spells a byte offset.
//
//   build/adv-wiregen > ../web/src/gen/wire.ts
#include "wire_table.h"

#include <stdio.h>
#include <string.h>

// snake_case -> camelCase.
static const char *camel(const char *s) {
    static char buf[4][64];
    static int ring;
    char *o = buf[ring = (ring + 1) & 3];
    int up = 0, k = 0;
    for (; *s && k < 62; s++) {
        if (*s == '_') { up = 1; continue; }
        o[k++] = (char)(up && *s >= 'a' && *s <= 'z' ? *s - 32 : *s);
        up = 0;
    }
    o[k] = 0;
    return o;
}

// adv_w_user_stats -> WUserStats
static const char *type_name(const char *s) {
    static char buf[4][64];
    static int ring;
    char *o = buf[ring = (ring + 1) & 3];
    if (strncmp(s, "adv_", 4) == 0) s += 4;
    int up = 1, k = 0;
    for (; *s && k < 62; s++) {
        if (*s == '_') { up = 1; continue; }
        o[k++] = (char)(up && *s >= 'a' && *s <= 'z' ? *s - 32 : *s);
        up = 0;
    }
    o[k] = 0;
    return o;
}

static const char *reader(int kind) {
    switch (kind) {
    case WK_U8: return "dv.getUint8(%s)";
    case WK_U16: return "dv.getUint16(%s, true)";
    case WK_U32: return "dv.getUint32(%s, true)";
    case WK_I32: return "dv.getInt32(%s, true)";
    case WK_F32: return "dv.getFloat32(%s, true)";
    case WK_I64: return "Number(dv.getBigInt64(%s, true))";
    case WK_U64: return "Number(dv.getBigUint64(%s, true))";
    default: return "0";
    }
}

int main(void) {
    printf("// GENERATED by adventurer/server/tools/wiregen.c from src/wire.h and src/wire_table.h. DO NOT EDIT.\n");
    printf("// Every offset and size below is the C compiler's. The server stamps WIRE_HASH into every answer;\n");
    printf("// a page whose hash differs was built from another layout and must refuse the bytes.\n\n");
    printf("export const WIRE_HASH = 0x%08x;\n\n", adv_wire_table_hash());
    printf("export const SIZE = {\n");
    for (size_t i = 0; i < ADV_WIRE_N_STRUCTS; i++) printf("  %s: %zu,\n", type_name(ADV_WIRE_STRUCTS[i].name), ADV_WIRE_STRUCTS[i].size);
    printf("} as const;\n\n");
    printf("function str(dv: DataView, off: number, len: number): string {\n");
    printf("  return new TextDecoder().decode(new Uint8Array(dv.buffer, dv.byteOffset + off, len));\n}\n\n");
    for (size_t s = 0; s < ADV_WIRE_N_STRUCTS; s++) {
        const char *sn = ADV_WIRE_STRUCTS[s].name;
        const char *tn = type_name(sn);
        // The interface.
        printf("export interface %s {\n", tn);
        for (size_t i = 0; i < ADV_WIRE_N_FIELDS; i++) {
            const adv_wire_field *f = &ADV_WIRE_FIELDS[i];
            if (strcmp(f->strct, sn) != 0) continue;
            size_t count = f->size / f->elem;
            if (f->kind == WK_STR) printf("  %s: string;\n", camel(f->field));
            else if (f->kind == WK_U64 && f->elem > 8) printf("  %s: WLeader[];\n", camel(f->field));
            else if (count > 1) printf("  %s: number[];\n", camel(f->field));
            else printf("  %s: number;\n", camel(f->field));
        }
        printf("}\n\n");
        // The reader.
        printf("export function read%s(dv: DataView, off: number): %s {\n", tn, tn);
        printf("  return {\n");
        for (size_t i = 0; i < ADV_WIRE_N_FIELDS; i++) {
            const adv_wire_field *f = &ADV_WIRE_FIELDS[i];
            if (strcmp(f->strct, sn) != 0) continue;
            size_t count = f->size / f->elem;
            char at[64];
            if (f->kind == WK_STR) {
                // A char[N] whose length is the struct's name_len field when it has one, else to the first NUL.
                printf("    %s: str(dv, off + %zu, nameLen(dv, off, %zu, %zu)),\n", camel(f->field), f->off, f->off, f->size);
            } else if (f->kind == WK_U64 && f->elem > 8) {
                printf("    %s: Array.from({ length: %zu }, (_, i) => readWLeader(dv, off + %zu + i * %zu)),\n", camel(f->field), count, f->off, f->elem);
            } else if (count > 1) {
                printf("    %s: [", camel(f->field));
                for (size_t k = 0; k < count; k++) {
                    snprintf(at, sizeof at, "off + %zu", f->off + k * f->elem);
                    printf(k ? ", " : "");
                    printf(reader(f->kind), at);
                }
                printf("],\n");
            } else {
                snprintf(at, sizeof at, "off + %zu", f->off);
                printf("    %s: ", camel(f->field));
                printf(reader(f->kind), at);
                printf(",\n");
            }
        }
        printf("  };\n}\n\n");
    }
    // name_len: the structs that carry a name carry its length right after the id (kind, name_len).
    printf("// A char[N]'s length: the struct's name_len byte when the layout has one (right after kind), else\n");
    printf("// up to the first NUL.\n");
    printf("function nameLen(dv: DataView, off: number, strOff: number, cap: number): number {\n");
    printf("  let n = 0;\n  while (n < cap && dv.getUint8(off + strOff + n) !== 0) n++;\n  return n;\n}\n\n");
    printf("// A list answer: the head, then n records of `size` bytes read by `read`.\n");
    printf("export function readList<T>(buf: ArrayBuffer, size: number, read: (dv: DataView, off: number) => T): T[] {\n");
    printf("  const dv = new DataView(buf);\n  const head = readWList(dv, 0);\n");
    printf("  if (head.hash !== WIRE_HASH) throw new Error('wire layout mismatch: rebuild the web (make -C adventurer/server)');\n");
    printf("  const out: T[] = [];\n  for (let i = 0; i < head.n; i++) out.push(read(dv, SIZE.WList + i * size));\n  return out;\n}\n");
    return 0;
}
