// The request: argv, checked. Nothing here reads a header or emits a line - it
// turns the command line into the globals the rest of the run reads, and prints
// the banner that says which request wrote a module.
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include "structgen.h"
#include "sg_args.h"
#include "sg_model.h"

const char *headers[MAXN], *roots[MAXN], *prefixes[MAXN], *snaps[MAXN], *writers[MAXN], *build, *out_ts, *out_swift, *out_kotlin, *out_hash_ts, *cwd = ".";
const char *kotlin_package;
const char *target = "wasm32";
int nheaders, nroots, nprefixes, nsnaps, nwriters, print_hash, snapshot_only;
int prefix_names[MAXN];
const char *sources[MAXSRC];
int nsources;
Link links[MAXLINK];
int nlinks;
const char *build_name_end;
const char *build_flags;

// The header both generated modules start with.
void emit_banner(FILE *fp) {
    fprintf(fp, "// GENERATED by tools/structgen - do not edit.\n// build: %.*s; roots: ", (int)(build_name_end - build), build);
    for (int i = 0; i < nroots; i++) fprintf(fp, "%s%s", i ? ", " : "", roots[i]);
    if (!nroots) fputs("none (constants only)", fp);
    fputc('\n', fp);
}

static void usage(void) {
    fputs("usage: structgen --cwd DIR --header H... --root T... --build NAME=FLAGS\n"
          "                 [--fields T=f1,f2,SIZE]... [--const PREFIX]...\n"
          "                 [--snapshot T]... [--count T.f=c]... [--writer T]... [--snapshot-only]\n"
          "                 [--target TRIPLE] [--ts OUT.ts] [--swift OUT.swift] [--hash-ts OUT.ts] [--print-hash]\n"
          "                 [--kotlin OUT.kt --kotlin-package PKG]\n"
          "       structgen --cwd DIR --header H... --build NAME=FLAGS (--const PREFIX | --names PREFIX)... --ts OUT.ts\n"
          "       structgen --cwd DIR --source C... --build NAME=FLAGS\n"
          "                 (--link LDFLAGS --exports-name IDENT [--exports-ts OUT.ts] [--check-wasm MODULE.wasm])...\n", stderr);
    exit(2);
}

void sg_args(int argc, char **argv) {
    for (int i = 1; i < argc; i++) {
        const char *a = argv[i];
        if (!strcmp(a, "--print-hash")) { print_hash = 1; continue; }
        if (!strcmp(a, "--snapshot-only")) { snapshot_only = 1; continue; }
        if (!strcmp(a, "--help") || !strcmp(a, "-h")) usage();
        if (strncmp(a, "--", 2)) die("unexpected argument %s", a);
        if (i + 1 >= argc || !strncmp(argv[i + 1], "--", 2)) die("%s needs a value", a);
        const char *v = argv[++i];
        if (!strcmp(a, "--header")) { if (nheaders == MAXN) die("too many --header"); headers[nheaders++] = v; }
        else if (!strcmp(a, "--root")) { if (nroots == MAXN) die("too many --root"); roots[nroots++] = v; }
        else if (!strcmp(a, "--const") || !strcmp(a, "--names")) {
            if (nprefixes == MAXN) die("too many --const and --names");
            prefix_names[nprefixes] = a[2] == 'n';
            prefixes[nprefixes++] = v;
        }
        else if (!strcmp(a, "--source")) { if (nsources == MAXSRC) die("too many --source"); sources[nsources++] = v; }
        else if (!strcmp(a, "--link")) { if (nlinks == MAXLINK) die("too many --link"); links[nlinks++].flags = v; }
        else if (!strcmp(a, "--exports-name") || !strcmp(a, "--exports-ts") || !strcmp(a, "--check-wasm")) {
            if (!nlinks) die("%s before any --link: it says something about the link it follows", a);
            Link *l = &links[nlinks - 1];
            const char **slot = a[2] == 'c' ? &l->check_wasm : a[10] == 'n' ? &l->name : &l->out_ts;
            if (*slot) die("two %s for one --link", a);
            *slot = slot == &l->name ? v : absolute(v);   // a path means where we were started, like every output
        }
        else if (!strcmp(a, "--snapshot")) { if (nsnaps == MAXN) die("too many --snapshot"); snaps[nsnaps++] = v; }
        else if (!strcmp(a, "--writer")) { if (nwriters == MAXN) die("too many --writer"); writers[nwriters++] = v; }
        else if (!strcmp(a, "--count")) {
            if (ncounts == MAXN) die("too many --count");
            Count *c = &counts[ncounts++];
            char *dot, *eq = NULL;
            c->type = xstrdup(v);
            if (!(dot = strchr(c->type, '.')) || !(eq = strchr(dot, '=')) || dot == c->type || eq == dot + 1 || !eq[1])
                die("--count must be TYPE.field=count_field");
            *dot = 0; *eq = 0;
            c->field = dot + 1; c->count = eq + 1;
        }
        else if (!strcmp(a, "--build")) { if (build) die("one --build per run (run once per build)"); build = v; }
        else if (!strcmp(a, "--ts")) out_ts = v;
        else if (!strcmp(a, "--swift")) out_swift = v;
        else if (!strcmp(a, "--kotlin")) out_kotlin = v;
        else if (!strcmp(a, "--kotlin-package")) kotlin_package = v;
        else if (!strcmp(a, "--hash-ts")) out_hash_ts = v;
        else if (!strcmp(a, "--target")) target = v;
        else if (!strcmp(a, "--cwd")) cwd = v;
        else if (!strcmp(a, "--fields")) {
            if (nspecs == MAXN) die("too many --fields");
            Spec *s = &specs[nspecs++];
            char *eq = strchr(s->type = xstrdup(v), '=');
            if (!eq || eq == s->type || !eq[1]) die("--fields must be TYPE=f1,f2,...");
            *eq = 0;
            for (char *tok = strtok(eq + 1, ","); tok; tok = strtok(NULL, ",")) {
                if (s->n == 256) die("too many fields for %s", s->type);
                s->names[s->n++] = tok;
            }
        }
        else die("unknown argument %s", a);
    }
    if (!build) usage();
    if (nlinks || nsources) {
        // AN EXPORTS RUN ANSWERS ONE QUESTION - what a link of these sources
        // exports - and it asks it of C FILES, one translation unit each, where
        // every other run asks one probe that includes headers. So the two do
        // not mix in one run, and saying so here is kinder than emitting half.
        if (!nlinks) die("--source without a --link: sources are what an exports run reads");
        if (!nsources) die("--link without a --source: the prototypes come from the C files the module is linked from");
        if (nheaders || nroots || nprefixes || nsnaps || nwriters || nspecs || ncounts || snapshot_only
            || out_ts || out_swift || out_kotlin || out_hash_ts || print_hash || kotlin_package)
            die("--link is a run of its own: it takes --cwd, --build, --target, --source, and per link --exports-name, --exports-ts and --check-wasm");
        for (int i = 0; i < nlinks; i++) {
            if (!links[i].name) die("--link needs --exports-name: the interface it becomes has to be called something");
            if (!links[i].out_ts && !links[i].check_wasm) die("nothing to do for %s: give --exports-ts and/or --check-wasm", links[i].name);
        }
    } else {
        if (!nheaders) usage();
        // A run with no --root holds constants and nothing else. It still has a
        // build, because a constant is whatever the headers say UNDER that
        // build's -D flags.
        if (!nroots && !nprefixes) die("nothing to read: give --root, --const and/or --names");
        if (!out_ts && !out_swift && !out_kotlin && !out_hash_ts && !print_hash) die("nothing to do: give --ts, --swift, --kotlin, --hash-ts and/or --print-hash");
    }
    if (out_swift && !nsnaps) die("--swift without a --snapshot: Swift gets value snapshots, not accessors");
    if (out_kotlin && !nsnaps) die("--kotlin without a --snapshot: Kotlin gets value snapshots, not accessors");
    if (out_kotlin && !kotlin_package) die("--kotlin needs --kotlin-package: a Kotlin file declares the package it is in");
    if (kotlin_package && !out_kotlin) die("--kotlin-package without --kotlin: nothing is being written in Kotlin");
    const char *eq = strchr(build, '=');
    if (!eq || eq == build) die("--build must be NAME=FLAGS");
    build_name_end = eq;
    build_flags = eq + 1;
    out_ts = absolute(out_ts);   // output paths are relative to where we were started, not to --cwd
    out_swift = absolute(out_swift);
    out_kotlin = absolute(out_kotlin);
    out_hash_ts = absolute(out_hash_ts);
    if (chdir(cwd)) die("cannot cd to %s", cwd);
}
