// embed.c - writes a file's bytes as a C string constant, so the binary
// carries sql/schema.sql (and later the admin console) and a deploy is one
// file. A tiny C tool rather than `xxd -i`, which is not on every Linux image.
//
//   build/embed <input> <symbol> > out.c
//
// emits  const char <symbol>[] = "...";  const unsigned long <symbol>_len = N;
// The string is NUL-terminated; _len does not count the NUL.
#include <stdio.h>

int main(int argc, char **argv) {
    if (argc != 3) { fprintf(stderr, "usage: embed <input> <symbol>\n"); return 2; }
    FILE *f = fopen(argv[1], "rb");
    if (!f) { perror(argv[1]); return 1; }
    printf("// GENERATED by c_base/tools/embed.c from %s - do not edit.\n", argv[1]);
    printf("const char %s[] =\n\"", argv[2]);
    unsigned long n = 0;
    int c, col = 0;
    while ((c = fgetc(f)) != EOF) {
        n++;
        if (c == '\n') { printf("\\n\"\n\""); col = 0; continue; }
        if (c == '"' || c == '\\') printf("\\%c", c);
        else if (c >= 0x20 && c < 0x7f && c != '?') putchar(c);   // '?' would risk a trigraph
        else printf("\\%03o", c);
        if (++col > 100) { printf("\"\n\""); col = 0; }
    }
    if (ferror(f)) { perror(argv[1]); fclose(f); return 1; }
    fclose(f);
    printf("\";\nconst unsigned long %s_len = %luUL;\n", argv[2], n);
    return 0;
}
