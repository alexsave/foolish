// gen_simtab - writes the constant tables the rollout engine (src/gd_sim.c)
// works from, as a C header (build/gd_simtab.h): per-byte popcount and lowest
// set bit, and the 5-byte card masks of each rank, each suit, and each card's
// higher cards of its suit. Build-time only; the cards are ids suit * 9 + rank.
#include <stdio.h>
#include <stdint.h>

static void mask(const char *name, int n, int (*has)(int, int)) {
    printf("static const uint8_t %s[%d][5] = {\n", name, n);
    for (int i = 0; i < n; i++) {
        uint8_t b[5] = { 0 };
        for (int c = 0; c < 36; c++) if (has(i, c)) b[c >> 3] |= (uint8_t)(1u << (c & 7));
        printf("    { 0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X },\n", b[0], b[1], b[2], b[3], b[4]);
    }
    printf("};\n");
}

static int is_rank(int r, int c) { return c % 9 == r; }
static int is_suit(int s, int c) { return c / 9 == s; }
static int is_higher(int a, int c) { return c / 9 == a / 9 && c % 9 > a % 9; }

int main(void) {
    printf("// Generated by tools/gen_simtab.c. Do not edit.\n");
    printf("static const uint8_t SIM_POP8[256] = {");
    for (int i = 0; i < 256; i++) printf("%s%d", i ? "," : "", __builtin_popcount((unsigned)i));
    printf("};\n");
    printf("// the lowest set bit of a byte (8 for none)\nstatic const uint8_t SIM_LOW8[256] = {");
    for (int i = 0; i < 256; i++) printf("%s%d", i ? "," : "", i ? __builtin_ctz((unsigned)i) : 8);
    printf("};\n");
    mask("SIM_RANK", 9, is_rank);
    mask("SIM_SUIT", 4, is_suit);
    mask("SIM_HIGHER", 36, is_higher);
    // every card of a set of ranks (a bit per rank), for "the cards of the
    // ranks on the table" in one lookup
    printf("static const uint8_t SIM_RANKSET[512][5] = {\n");
    for (int set = 0; set < 512; set++) {
        uint8_t b[5] = { 0 };
        for (int c = 0; c < 36; c++) if ((set >> (c % 9)) & 1) b[c >> 3] |= (uint8_t)(1u << (c & 7));
        printf("    { 0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X },\n", b[0], b[1], b[2], b[3], b[4]);
    }
    printf("};\n");
    // the endgame solver's hash (src/gd_sim.c, Pearson's: a lane is
    // h = T[h ^ byte]) needs a fixed permutation of the bytes; this one is a
    // Fisher-Yates walk driven by a fixed xorshift, a constant like any other
    // table here (nothing at run time draws from it)
    {
        uint8_t t[256];
        uint32_t x = 0x9E3779B9u;
        for (int i = 0; i < 256; i++) t[i] = (uint8_t)i;
        for (int i = 255; i > 0; i--) {
            x ^= x << 13; x ^= x >> 17; x ^= x << 5;
            int j = (int)(x % (uint32_t)(i + 1));
            uint8_t s = t[i]; t[i] = t[j]; t[j] = s;
        }
        printf("static const uint8_t SIM_PEARSON[256] = {");
        for (int i = 0; i < 256; i++) printf("%s%d", i ? "," : "", t[i]);
        printf("};\n");
    }
    printf("static const uint8_t SIM_MOD3[256] = {");
    for (int i = 0; i < 256; i++) printf("%s%d", i ? "," : "", i % 3);
    printf("};\n");
    // 2 to the k, for subset counters without a variable shift
    printf("static const uint16_t SIM_POW2[16] = {");
    for (int i = 0; i < 16; i++) printf("%s%u", i ? "," : "", 1u << i);
    printf("};\n");
    return 0;
}
