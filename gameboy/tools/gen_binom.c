// gen_binom - writes the binomial table gd_rules.c includes (C(n, k) for
// n <= 36, k <= 18, saturated at 0xFFFFFFFF) as a C header, so the ROM gets
// it as constant data instead of computing it. Build-time only.
#include <stdint.h>
#include <stdio.h>

int main(void) {
    static uint64_t c[37][37];
    for (int n = 0; n <= 36; n++) {
        c[n][0] = 1;
        for (int k = 1; k <= n; k++) c[n][k] = c[n - 1][k - 1] + (k <= n - 1 ? c[n - 1][k] : 0);
    }
    printf("// Generated by tools/gen_binom.c. Do not edit.\n");
    printf("static const uint32_t gd_binom_tab[37][19] = {\n");
    for (int n = 0; n <= 36; n++) {
        printf("    {");
        for (int k = 0; k <= 18; k++) {
            uint64_t v = k <= n ? c[n][k] : 0;
            if (v > 0xFFFFFFFFu) v = 0xFFFFFFFFu;
            printf("%s%lluu", k ? "," : "", (unsigned long long)v);
        }
        printf("},\n");
    }
    printf("};\n");
    return 0;
}
