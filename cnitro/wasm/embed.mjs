// Embeds the compiled rules kernel as a base64 TS module so every runtime
// (Deno edge, Node/tsx, browsers) can import it with zero asset plumbing.
// Regenerate with `make wasm` from cnitro/.
import { readFileSync, writeFileSync } from 'fs';

const [src, dst] = process.argv.slice(2);
const bytes = readFileSync(src);
const b64 = bytes.toString('base64');

writeFileSync(dst, `// GENERATED by cnitro/wasm/embed.mjs — do not edit.
// Source of truth: cnitro/src/game.c + legal.c (+ wasm/wasm_api.c bridge).
// Rebuild with: cd cnitro && make wasm
// ${bytes.length} bytes of wasm32.
export const RULES_WASM_B64 =
  '${b64.match(/.{1,120}/g).join("' +\n  '")}';
`);
console.log(`embedded ${src} (${bytes.length} bytes) -> ${dst}`);
