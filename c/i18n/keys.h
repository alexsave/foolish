// Every string the phone app and the iMessage board render, by name. ONE key
// space, shared by both hosts and by the website.
//
// THIS FILE IS SOURCE, and it is the only place a key is declared. The rest -
// the TypeScript the web imports and the Swift FoolishKit compiles - is written
// from it by tools/datagen at build time and is not committed. Adding a string
// is adding a line here and a line in each language file; a language that then
// does not carry it fails the build (see c/i18n/README.md).
//
// NOTHING HERE IS COMPILED INTO A SHIPPED MODULE. c/i18n is outside c/src and
// appears in no *_SRC list in c/Makefile, on purpose: twenty-five languages of
// translations is around 150 KB of string data, and bots.wasm.gz is downloaded
// by every visitor to the site. The C is a source of truth for a generator, not
// a translation unit anybody links. The gate is
// e2e/validation/i18n_source_of_truth.test.ts, whose first test ('no translated
// string reaches the shipped wasm') gunzips the shipped module and searches it.
//
// THE ORDER IS ALPHABETICAL BY KEY and means nothing else. A generated module is
// keyed by these names, never by position, so the enum's values are an internal
// detail - see tools/datagen's header on why that is the whole safety argument.
