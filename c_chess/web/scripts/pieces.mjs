// pieces.mjs - inlines the piece set (pieces/*.svg) into src/app/pieces.css as data URIs, one class
// per piece (.p1 .. .p6 white, .p9 .. .p14 black, as the kernel's board numbers them), so the board
// draws with no request beyond the page's own stylesheet. A build output, never committed.
import { readFileSync, writeFileSync } from 'node:fs';

const order = ['P', 'N', 'B', 'R', 'Q', 'K'];
let css = '/* GENERATED by scripts/pieces.mjs from pieces/ (cburnett, GPLv2+) - do not edit */\n';
for (const [ci, c] of [['w', 0], ['b', 8]]) {
  order.forEach((t, i) => {
    const svg = readFileSync(`pieces/${ci}${t}.svg`, 'utf8').replace(/\s+/g, ' ').trim();
    // URL-escaped rather than base64: smaller, and it gzips (the quotes become single ones)
    const esc = svg.replace(/"/g, "'").replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E');
    css += `.p${1 + i + c}{background-image:url("data:image/svg+xml,${esc}")}\n`;
  });
}
writeFileSync('src/app/pieces.css', css);
console.log(`pieces.css: ${css.length} B`);
