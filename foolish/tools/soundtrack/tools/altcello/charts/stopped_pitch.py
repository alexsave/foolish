"""Stopped-pitch calibration: every semitone 1..14 on every string, played by the EXPERT player with vibrato off, pitch measured from the
48 kHz pressure. The correction (cents to ADD to the ideal finger position, instrument_cello.c STOP_CENTS_TABLE) is the negative of the
measured error on top of the table the binary was built with.

    python -I charts/stopped_pitch.py measure TAG        render + measure, prints the error table, writes out/player/TAG_stop.txt
    python -I charts/stopped_pitch.py apply TAG          add the negated errors to the table in instrument_cello.c (between the markers)
"""
import os, sys, subprocess, re
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import player_gates as G  # noqa: E402
M = G.M
ROOT = G.ROOT
EXE = os.path.join(ROOT, "altcello")
OPEN = [36, 43, 50, 57]
NAMES = "CGDA"
SRC = os.path.join(ROOT, "instrument_cello.c")


def table_in_source():
    s = open(SRC).read()
    a, b = s.index("/*STOP_CENTS_BEGIN*/"), s.index("/*STOP_CENTS_END*/")
    nums = re.findall(r"-?\d+\.?\d*(?:e-?\d+)?", s[a:b].split("#define STOP_CENTS_TABLE")[1])
    nums = [float(x) for x in nums]
    T = np.zeros((4, 15))
    if len(nums) == 60:
        T = np.array(nums).reshape(4, 15)
    return T


def render(tag):
    os.makedirs(G.TMP, exist_ok=True)
    notes = os.path.join(G.TMP, tag + "_notes.txt")
    lines, t = [], 0.5
    for s in range(4):
        for semis in range(1, 15):
            lines.append("%.3f 1.2 %d 0.7 %s 0 - - 0" % (t, OPEN[s] + semis, NAMES[s]))
            t += 1.6
    open(notes, "w").write("\n".join(lines) + "\n")
    wav = os.path.join(G.TMP, tag + ".wav")
    r = subprocess.run(["nice", EXE, "render", notes, wav, "--room", "off"], capture_output=True, text=True, check=True)
    print(r.stdout.strip())
    return wav


def measure(tag):
    wav = render(tag)
    y = M.load_audio(wav)
    err = np.full((4, 15), np.nan)
    t = 0.5
    for s in range(4):
        for semis in range(1, 15):
            midi = OPEN[s] + semis
            a, b = int((t + 0.4) * 48000), int((t + 1.0) * 48000)
            seg = y[int((t - 0.1) * 48000):int((t + 1.3) * 48000)]
            tf, f0 = M.track_f0(seg, 48000, M.midi_hz(midi), None, t_offset=0)
            sel = (tf >= 0.5) & (tf <= 1.1)
            err[s, semis] = 1200 * np.log2(np.median(f0[sel]) / M.midi_hz(midi))
            t += 1.6
    np.savetxt(os.path.join(G.TMP, tag + "_stop.txt"), err, fmt="%.2f")
    print("pitch error (cents, measured - nominal) per string C G D A (rows), semitone 0..14 (columns):")
    for s in range(4):
        print(NAMES[s], " ".join("%6.1f" % v for v in err[s]))
    return err


def apply(tag):
    err = np.loadtxt(os.path.join(G.TMP, tag + "_stop.txt"))
    err = np.nan_to_num(err)
    T = table_in_source() - err
    rows = ["{" + ", ".join("%.2f" % v for v in T[s]) + "}" for s in range(4)]
    s = open(SRC).read()
    a, b = s.index("/*STOP_CENTS_BEGIN*/"), s.index("/*STOP_CENTS_END*/")
    new = "/*STOP_CENTS_BEGIN*/\n/* GENERATED by charts/stopped_pitch.py (measured pitch error of every stopped semitone on every string, EXPERT player, vibrato off, 1 s of\n * steady pitch; cents to ADD to the ideal pitch when placing the finger; applied additively over iterations: the pad's mass and\n * finite stiffness flatten the string, more at higher positions). */\n#define STOP_CENTS_TABLE \\\n    {" + ", \\\n     ".join(rows) + "}\n"
    open(SRC, "w").write(s[:a] + new + s[b:])
    print("table written")


if __name__ == "__main__":
    {"measure": measure, "apply": apply}[sys.argv[1]](sys.argv[2])
