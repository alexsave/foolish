"""Generate the playability table of instrument_cello.c (between the PLAYABILITY markers) from the GRID sweeps of charts/iter2_run.sh.

    /Users/alex/Dev/soundtrack-tools/venv/bin/python -I charts/playability_table.py [--check]

Input: /Users/alex/Music/foolish_cities_v5/alt_cello/iter2/grid_<STRING>_b<beta>_v<vB>.txt (rows: F ours simple ...).
A force is Helmholtz when BOTH classifiers (ours: one slip per period; simple: one dominant slip per period) accept it. The entry
is the longest contiguous run of such forces: fmin, fmax = its first and last grid force, fcentre = sqrt(fmin fmax); all zero
when no force passes. The header comment names the commit of the working tree the sweeps were run on.
"""
import math, os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "instrument_cello.c")
D = os.environ.get("ITER2_DIR", "/Users/alex/Music/foolish_cities_v5/alt_cello/iter2")
STRINGS = ["C2", "G2", "D3", "A3"]
BETA = [0.07, 0.10, 0.14]
VB = [0.05, 0.10, 0.20]


def tag(x):
    return ("%g" % x) if x != 0.1 else "0.1"


def band(path):
    rows = [ln.split() for ln in open(path) if not ln.startswith("#") and ln.strip()]
    F = [float(r[0]) for r in rows]
    ok = [int(r[1]) == 1 and int(r[2]) == 1 for r in rows]
    best = (0, -1)
    i = 0
    while i < len(F):
        if ok[i]:
            j = i
            while j + 1 < len(F) and ok[j + 1]: j += 1
            if j - i + 1 > best[0]: best = (j - i + 1, i)
            i = j + 1
        else: i += 1
    if best[0] == 0: return (0.0, 0.0, 0.0)
    lo, hi = F[best[1]], F[best[1] + best[0] - 1]
    return (lo, hi, math.sqrt(lo * hi))


def table():
    t = {}
    for s in STRINGS:
        for b in BETA:
            for v in VB:
                p = os.path.join(D, "grid_%s_b%s_v%s.txt" % (s, tag(b), tag(v)))
                t[(s, b, v)] = band(p)
    return t


def main():
    t = table()
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    dirty = subprocess.run(["git", "status", "--porcelain", "--", "."], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    lines = ["/*PLAYABILITY_BEGIN*/",
             "/* GENERATED by charts/playability_table.py from the sweeps of charts/iter2_run.sh GRID (sweep_tool ours, body on, all strings,",
             " * 6 s runs, last 0.5 s classified, 20 forces log spaced 0.03-5 N, both classifiers must accept); source commit %s%s. Do not edit.**" % (head, " (plus the generated table itself)" if dirty else ""),
             " * Per string (C2 G2 D3 A3), per beta {0.07, 0.10, 0.14}, per v_B {0.05, 0.10, 0.20} m/s: {F_min, F_max, geometric centre} in N of the",
             " * longest contiguous Helmholtz band; {0, 0, 0} = none. The player controller stays inside it with margin. */",
             "#define PLAYABILITY_TABLE \\", "    {\\"]
    lines[2] = lines[2].replace(".**", ".")
    for si, s in enumerate(STRINGS):
        lines.append("     /* %s */ {\\" % s)
        for b in BETA:
            ent = ", ".join("{%.6g, %.6g, %.6g}" % t[(s, b, v)] for v in VB)
            lines.append("         {%s}%s \\" % (ent, "," if b != BETA[-1] else ""))
        lines.append("     }%s \\" % ("," if si < 3 else ""))
    lines.append("    }")
    lines.append("/*PLAYABILITY_END*/")
    src = open(SRC).read()
    new = re.sub(r"/\*PLAYABILITY_BEGIN\*/.*?/\*PLAYABILITY_END\*/", lambda m: "\n".join(lines), src, flags=re.S)
    if "--check" in sys.argv:
        print("table matches" if new == src else "table differs"); return
    open(SRC, "w").write(new)
    for s in STRINGS:
        for b in BETA:
            print(s, "beta %.2f" % b, "  ".join("vB %.2f: %.3f-%.3f (x%.2f)" % ((v,) + t[(s, b, v)][:2] + ((t[(s, b, v)][1] / t[(s, b, v)][0]) if t[(s, b, v)][0] else 0,)) for v in VB))


main()
