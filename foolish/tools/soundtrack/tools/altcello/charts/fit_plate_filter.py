"""ALT-CELLO plate radiation filter fit (stage 2 iteration 3).

Fits a minimum-phase analog filter  H(s) = K prod (1 + s/z_i) / prod (1 + s/p_i)  (real zeros and poles, rad/s)
to |sqrt(sigma(f))|, sigma the baffled-plate radiation efficiency of radiate_body.h (edge-mode Maidanik form below
f_c, 1/sqrt(1 - f_c/f) above, clamped to 1), on a log grid 50 Hz - 20 kHz, minimising the maximum dB error.
Writes radiate_plate_table.c (one table per f_c). Plain text output, no JSON.

    nice /Users/alex/Dev/soundtrack-tools/venv/bin/python -I charts/fit_plate_filter.py
"""
import datetime, os, sys
import numpy as np
from scipy.optimize import least_squares, minimize

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C_AIR, AREA, PERIM = 343.0, 0.17, 2.0
FC_LIST = [2000.0, 2500.0, 3000.0, 3500.0, 4000.0, 5000.0]
NSEC = 6
F = np.geomspace(50.0, 20000.0, 400)
FS = 96000.0
# the bilinear transform at fs maps the digital frequency f to the analog frequency (fs/pi) tan(pi f/fs): the analog model is evaluated there,
# so the realised digital filter at 96 kHz (the simulation rate) is the fit
FA = FS / np.pi * np.tan(np.pi * F / FS)


def sigma(f, fc):
    f = np.asarray(f, float)
    out = np.ones_like(f)
    lam = C_AIR / fc
    pre = PERIM * lam / (4 * np.pi ** 2 * AREA)
    lo = f < fc
    a = np.sqrt(f[lo] / fc)
    with np.errstate(all="ignore"):
        s = pre * ((1 - a * a) * np.log((1 + a) / (1 - a)) + 2 * a) / (1 - a * a) ** 1.5
    s = np.where(np.isfinite(s), s, 1.0)
    out[lo] = np.minimum(1.0, s)
    return out


def model_db(p, f):
    lk, lz, lp = p[0], p[1:1 + NSEC], p[1 + NSEC:]
    d = 20 * lk
    for z in np.exp(lz): d = d + 10 * np.log10(1 + (f / z) ** 2)
    for q in np.exp(lp): d = d - 10 * np.log10(1 + (f / q) ** 2)
    return d


# every pole and zero between 30 Hz and 60 kHz (no integrator-like pole near DC, which would let a random-walk drift into the
# summed modal velocities), K free
LZ = (np.log(30.0), np.log(60000.0))  # Hz
LO = np.concatenate([[-5.0], np.full(2 * NSEC, LZ[0])])
HI = np.concatenate([[5.0], np.full(2 * NSEC, LZ[1])])
BND = [(-5.0, 5.0)] + [LZ] * (2 * NSEC) + [(0.0, 20.0)]


def knee(fc):
    """first frequency where the clamped sigma reaches 1"""
    for f in np.geomspace(50.0, fc, 4000):
        if sigma([f], fc)[0] >= 1.0: return f
    return fc


def fit(fc):
    target = 10 * np.log10(sigma(F, fc))  # 20 log10 sqrt(sigma)
    # the hard clamp of sigma at 1 is a kink that six real sections cannot follow: the error is weighted 1/2 in a window
    # 0.85 - 1.1 x the knee (it may be twice as large there), and minimised everywhere else
    fk = knee(fc)
    wt = np.where((F >= 0.85 * fk) & (F <= 1.1 * fk), 0.5, 1.0)
    best = None
    rng = np.random.default_rng(1)
    for trial in range(14):
        lz0 = np.log(np.geomspace(100, fc * 0.9, NSEC) * rng.uniform(0.7, 1.3, NSEC))
        lp0 = np.log(np.geomspace(150, fc * 1.5, NSEC) * rng.uniform(0.7, 1.3, NSEC))
        p0 = np.concatenate([[np.log10(0.1)], lz0, lp0])
        r = least_squares(lambda p: (model_db(p, FA) - target) * wt, p0, method="trf", bounds=(LO, HI), max_nfev=800)
        e = np.max(np.abs(r.fun))
        if best is None or e < best[0]: best = (e, r.x)
    e0, p = best
    # minimax polish: minimise t subject to |err| <= t
    x0 = np.concatenate([p, [e0]])
    cons = [{"type": "ineq", "fun": lambda x: x[-1] - (model_db(x[:-1], FA) - target) * wt},
            {"type": "ineq", "fun": lambda x: x[-1] + (model_db(x[:-1], FA) - target) * wt}]
    r = minimize(lambda x: x[-1], x0, constraints=cons, method="SLSQP", bounds=BND, options={"maxiter": 600, "ftol": 1e-9})
    x = r.x if np.max(np.abs((model_db(r.x[:-1], FA) - target) * wt)) < e0 else x0
    p = x[:-1]
    err = np.abs(model_db(p, FA) - target)
    return p, np.max(err[wt == 1.0]), np.max(err)


def main():
    lines = []
    for fc in FC_LIST:
        p, e, eall = fit(fc)
        z = np.sort(2 * np.pi * np.exp(p[1:1 + NSEC])); q = np.sort(2 * np.pi * np.exp(p[1 + NSEC:]))
        print("f_c %.0f: max error %.3f dB outside the knee window, %.3f dB overall, K %.5f" % (fc, e, eall, 10 ** p[0]), flush=True)
        lines.append((fc, e, eall, 10 ** p[0], z, q))
    path = os.path.join(ROOT, "radiate_plate_table.c")
    with open(path, "w") as f:
        f.write("/* GENERATED by charts/fit_plate_filter.py on %s. Do not edit.\n" % datetime.date.today().isoformat())
        f.write(" * Minimum-phase analog fit H(s) = K prod(1 + s/z_i) / prod(1 + s/p_i), real zeros z_i and poles p_i (rad/s),\n")
        f.write(" * to |sqrt(sigma(f))|, sigma of radiate_body.h (A 0.17 m^2, P 2.0 m, c 343 m/s), on a log grid 50 Hz - 20 kHz, evaluated at the\n * bilinear-warped analog frequencies of fs = 96 kHz (so the DIGITAL filter at 96 kHz is the fit; other rates drift above 10 kHz),\n")
        f.write(" * minimax in dB (error weighted 1/2 in a window 0.85-1.1 x the knee where the hard clamp sigma = 1 starts);\n * one row per supported critical frequency f_c; the max errors are in the comment of each row. */\n")
        f.write('#include "radiate_body.h"\n\n')
        f.write("const PlateFit radiate_plate_fits[RADIATE_NFC] = {\n")
        for fc, e, eall, k, z, q in lines:
            f.write("    /* f_c %.0f Hz, max error %.3f dB outside the knee window, %.3f dB overall */\n    {%.1f, %.8g,\n     {%s},\n     {%s}},\n" % (
                fc, e, eall, fc, k, ", ".join("%.8g" % x for x in z), ", ".join("%.8g" % x for x in q)))
        f.write("};\n")


if __name__ == "__main__":
    main()
