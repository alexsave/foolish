"""Writes the WEDGE block of instrument_cello.c: per string (C2 G2 D3 A3) the bow acceleration a (m/s^2) and the attack force F (N), stored as the slope k = F / a.
The values are the choice of the scans of charts/wedge_scan.py (out/wedge/scan_s5..s7: G2 on C, D3 on G, A3 on D, 6 seeds, hold 0.1 s); the A string was not
scanned on its own (the open A3 map, out/wedge/map_A3open.txt, has its good cells at 0.86-1.16 N) and takes the D string's value.
    python -I charts/wedge_table.py A_C F_C A_G F_G A_D F_D A_A F_A
"""
import os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
v = [float(x) for x in sys.argv[1:9]]
acc = [v[0], v[2], v[4], v[6]]; F = [v[1], v[3], v[5], v[7]]
k = [f / a for f, a in zip(F, acc)]
rev = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=ROOT).stdout.strip()
blk = """/*WEDGE_BEGIN*/
/* GENERATED by charts/wedge_table.py from the wedge scans of charts/wedge_scan.py (the real expert player on G2 on C, D3 on G, A3 on D, 6 seeds each, force held 0.1 s
 * after the bow reaches speed) and the Guettler maps of charts/wedge_run.sh (thermal bow, beta 0.1, v_end 0.12 m/s, force landed 20 ms before the motion); the tools
 * are at commit %s (the generated values themselves are in the next commit). Do not edit.
 * Per string (C2 G2 D3 A3): the bow acceleration (m/s^2) and the wedge slope (N per m/s^2); the attack force is slope * acceleration:
 * force %s N at %s m/s^2. */
#define WEDGE_ACC {%s}
#define WEDGE_K {%s}
/*WEDGE_END*/""" % (rev, ", ".join("%g" % f for f in F), ", ".join("%g" % a for a in acc), ", ".join("%g" % a for a in acc), ", ".join("%.5g" % x for x in k))
p = os.path.join(ROOT, "instrument_cello.c")
s = open(p).read()
s = re.sub(r"/\*WEDGE_BEGIN\*/.*?/\*WEDGE_END\*/", lambda m: blk, s, flags=re.S)
open(p, "w").write(s)
print(blk)
