"""Writes tables.h: the measured tables the C models read (the models' .npy files and the deal thumb slide's
template), as plain C arrays. Run once from tools/soundgen whenever an analysis rewrites a table:
    python3 -I c/tables.py > c/tables.h
The .npy files stay the source; this header is their committed copy for the build, which runs no numpy."""
import wave, numpy as np
SR = 48000
T = {}
def put(name, a): T[name] = np.asarray(a, float)
for name, path in [
    ("CS40", "throwin/an/cs40.npy"),
    ("DEAL_CLICK", "deal/an/click_spec.npy"), ("DEAL_BED", "deal/an/bed_spec.npy"),
    ("LAND4_CLICK", "deal/an/land4_click_spec.npy"), ("LAND4_BED", "deal/an/land4_bed_spec.npy"),
    ("TIN_STRIKE", "throwin/an/tin_strike_spec.npy"), ("TIN_BED", "throwin/an/tin_bed_spec.npy"), ("TIN_FIT", "throwin/an/tin_fit.npy"),
    ("TGRAB_SPEC", "throwin/an/tgrab_spec.npy"), ("TGRAB_FIT", "throwin/an/tgrab_fit.npy"),
    ("COV_STRIKE", "cover/an/cov_strike_spec.npy"), ("COV_BED", "cover/an/cov_bed_spec.npy"), ("COV_FIT", "cover/an/cov_fit.npy"),
    ("FLIP_SLIDE", "flip/an/flip_slide_spec.npy"), ("FLIP_SNAP", "flip/an/flip_snap_spec.npy"), ("FLIP_WHUP", "flip/an/flip_whup_spec.npy"),
    ("FLIP_SFIT", "flip/an/flip_slide_fit.npy"), ("FLIP_FIT", "flip/an/flip_fit.npy"),
    ("DECK_CLAT", "flip/an/deck_clatter_spec.npy"), ("DECK_CONTACT", "flip/an/deck_contact_spec.npy"),
    ("DECK_BED", "flip/an/deck_bed_spec.npy"), ("DECK_FIT", "flip/an/deck_fit.npy"),
    ("PASS_SPEC", "pass/an/pass_spec.npy"), ("PASS_FIT", "pass/an/pass_fit.npy"),
    ("SCR_SPEC", "discard/an/scr_spec.npy"), ("SCR_FIT", "discard/an/scr_fit.npy"), ("SCR_DUR", "discard/an/scr_dur.npy"),
    ("LIFT_SPEC", "discard/an/lift_spec.npy"), ("LIFT_FIT", "discard/an/lift_fit.npy"),
    ("PLACE_SPEC", "discard/an/place_spec.npy"), ("PLACE_FIT", "discard/an/place_fit.npy"),
    ("INS_SPEC", "discard/an/ins_spec.npy"), ("INS_FIT", "discard/an/ins_fit.npy"), ("INS_DUR", "discard/an/ins_dur.npy"),
    ("PLIFT_SPEC", "discard/an/plift_spec.npy"), ("PLIFT_FIT", "discard/an/plift_fit.npy"),
]:
    put(name, np.load(path))
for name, path in [("SCR_ENV", "discard/an/scr_env.npy"), ("INS_ENV", "discard/an/ins_env.npy"),
                   ("LIFT_ENV", "discard/an/lift_env.npy"), ("PLACE_ENV", "discard/an/place_env.npy"),
                   ("PLIFT_ENV", "discard/an/plift_env.npy")]:
    e = np.load(path); put(name + "_X", e[0]); put(name + "_LO", e[1]); put(name + "_HI", e[2])
# the deal's thumb slide: thumb2.py's template, the five real slides' mean 1/12-octave spectrum, 100 Hz-20 kHz
def load(p):
    with wave.open(p) as w: return np.frombuffer(w.readframes(w.getnframes()), np.int16) / 32768
cs = np.geomspace(100, 20000, 160); specs = []
for i in range(1, 6):
    x = load(f"deal/parts/real_thumb_{i}.wav"); h = 48; e = np.sqrt(np.convolve(x ** 2, np.ones(h) / h, "same")); a = np.where(e > e.max() * 0.2)[0]; y = x[a[0]:a[-1]]
    n = 8192; y = np.pad(y, (0, max(0, n - len(y))))[:n]; S = np.abs(np.fft.rfft(y * np.hanning(n))) ** 2; f = np.fft.rfftfreq(n, 1 / SR)
    specs.append(np.array([10 * np.log10(S[(f >= c * 2 ** (-1 / 24)) & (f < c * 2 ** (1 / 24))].mean() + 1e-20) for c in cs]))
tmpl = np.mean(specs, 0); tmpl -= tmpl.max()
put("THUMB_CS", cs); put("THUMB_TMPL", tmpl)
print("// GENERATED by tools/soundgen/c/tables.py from the models' .npy tables - do not edit.")
print("// The measured tables the C models read; the Python in each model folder is their source.")
print("#ifndef SOUNDGEN_TABLES_H\n#define SOUNDGEN_TABLES_H")
for k, v in T.items():
    v = np.where(np.isnan(v), np.nan, v)
    body = ", ".join("NAN" if np.isnan(x) else repr(float(x)) for x in v)
    print(f"#define {k}_N {len(v)}\nstatic const double {k}[{len(v)}] = {{ {body} }};")
print("#endif")
