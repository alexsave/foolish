#!/usr/bin/env bash
# lint_no_soundtrack.sh - the iMessage product ships the game's sound effects and
# NOTHING ELSE: no music, no soundtrack, no stray audio file. Runs in CI beside
# lint_architecture.sh and locally; exits non-zero on any violation. Portable -
# no Xcode needed.
#
# Why a lint: tools/soundtrack is the web's music tool. It has no business in a
# build that has to stay small and review-clean, and nothing compiles or links it
# in today, so nothing but this check would notice the day a project.yml line, a
# dropped-in .m4a or a widened copy in bundle_sounds.sh pulled it in.
#
#   1. Source side: project.yml never names tools/soundtrack, and no audio file
#      lives in a source directory the Messages targets compile (FoolishMessagesApp,
#      FoolishMessages, FoolishKit, and the sdk/swift and shared/swift sources
#      FoolishKit compiles). The sounds are GENERATED by soundgen into
#      public/audio/gen and are never committed, so there is nothing to allow.
#   2. bundle_sounds.sh (FoolishKit's only audio build phase) copies from
#      soundgen's output (public/audio/gen) and only the files soundgen's own
#      takes.tsv lists.
#   3. Built side, when given an .app (or .appex) path: audio only inside
#      FoolishKit.framework/sounds, none of it larger than 64 KB.
#
# Usage:
#   ios/scripts/lint_no_soundtrack.sh
#   ios/scripts/lint_no_soundtrack.sh path/to/Foolish.app
set -euo pipefail
cd "$(dirname "$0")/.."   # ios/

app="${1:-}"
fail=0
note() { echo "  ✗ $1"; fail=1; }

AUDIO_NAMES=(-iname '*.m4a' -o -iname '*.mp3' -o -iname '*.wav' -o -iname '*.caf' -o -iname '*.aac'
             -o -iname '*.aif' -o -iname '*.aiff' -o -iname '*.flac' -o -iname '*.ogg')
MAX_SOUND_BYTES=65536

echo "[lint] project.yml never names tools/soundtrack…"
if [ -f project.yml ]; then
  # Comment lines may discuss it; a line that is spec does not.
  if grep -nE '^[^#]*soundtrack' project.yml; then
    note "project.yml: names soundtrack - the music tool must stay out of the iMessage product"
  fi
else
  note "project.yml: missing"
fi

echo "[lint] no audio file in the Messages targets' source directories…"
for dir in FoolishMessagesApp FoolishMessages FoolishKit ../sdk/swift ../../shared/swift; do
  [ -d "$dir" ] || continue
  while IFS= read -r f; do
    [ -n "$f" ] && note "$f: an audio file in a source directory (the sounds are generated by soundgen, never committed)"
  done < <(find "$dir" \( -name build -o -name .build \) -prune -o -type f \( "${AUDIO_NAMES[@]}" \) -print)
  while IFS= read -r f; do
    [ -n "$f" ] && note "$f: names soundtrack"
  done < <(grep -rIl -i 'tools/soundtrack' "$dir" --include='*.yml' --include='*.json' --include='*.plist' \
             --include='*.sh' --include='*.xcconfig' --include='Makefile' 2>/dev/null || true)
done

echo "[lint] bundle_sounds.sh copies only soundgen's takes…"
bs=scripts/bundle_sounds.sh
if [ ! -f "$bs" ]; then
  note "$bs: missing"
else
  if grep -nE '^[^#]*soundtrack' "$bs"; then
    note "$bs: names soundtrack"
  fi
  # The one source directory, the one list, and nothing that reads another place.
  grep -qF 'gen="$root/public/audio/gen"' "$bs" \
    || note "$bs: no longer reads from soundgen's output (public/audio/gen)"
  grep -qF '$root/tools/soundgen/build/wav/takes.tsv' "$bs" \
    || note "$bs: no longer limited to soundgen's takes.tsv list"
  grep -qF 'for f in $names' "$bs" \
    || note "$bs: no longer copies exactly the files takes.tsv names"
  # Every cp / rsync / ditto source must be under $gen.
  while IFS= read -r line; do
    case "$line" in
      *'cp "$gen/$f" "$dest/$f"'*) ;;
      *) note "$bs: copies from somewhere other than soundgen's output: $line" ;;
    esac
  done < <(grep -nE '^[^#]*(^|[[:space:];&|])(cp|rsync|ditto|install|ln)[[:space:]]' "$bs" | sed -E 's/^[0-9]+:[[:space:]]*//' || true)
fi

if [ -n "$app" ]; then
  echo "[lint] built app: audio only in FoolishKit.framework/sounds, each file ≤ 64 KB ($app)…"
  if [ ! -d "$app" ]; then
    note "$app: not a directory"
  else
    while IFS= read -r f; do
      [ -z "$f" ] && continue
      case "$f" in
        */FoolishKit.framework/sounds/*)
          size=$(stat -f %z "$f" 2>/dev/null || stat -c %s "$f")
          if [ "$size" -gt "$MAX_SOUND_BYTES" ]; then
            note "$f: $size bytes, over the $MAX_SOUND_BYTES-byte limit for a sound effect"
          fi ;;
        *) note "$f: an audio file outside FoolishKit.framework/sounds" ;;
      esac
    done < <(find "$app" -type f \( "${AUDIO_NAMES[@]}" \))
  fi
fi

if [ "$fail" -eq 0 ]; then
  echo "[lint] no soundtrack OK"
else
  echo "[lint] no soundtrack FAILED"
  exit 1
fi
