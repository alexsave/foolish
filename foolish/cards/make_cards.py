#!/usr/bin/env python3
"""Foolish promo playing cards: print-ready PNGs for MakePlayingCards (MPC).

One back (the app's own IFS fern, rendered by fern.c, in CardBack.tsx's red frame)
and one face per QR source, in two face layouts drawn from CardFace.tsx's default
theme by headless Chrome. Every QR is decoded back from the final PNG and checked
against the exact payload. See README.md for the commands.
"""

import argparse
import hashlib
import os
import subprocess
import sys
import tempfile

import html
import shutil

import cv2
import numpy as np
import segno
from PIL import Image, ImageCms, ImageDraw, ImageFont

# ---- edit me -------------------------------------------------------------------------
# One card per source: (short path, name). The QR carries the payload form's prefix +
# short path, all upper-case so the QR stays in alphanumeric mode. The printed URL on
# the card is always the clean "foolish.cards".
# Every short path must hold at least one character outside the game-id alphabet
# (GAME_ID_ALPHABET below, from foolish/server/src/store/game_id.h) and must not be
# GAME_ID_LEN long, so it can never be read as a game id. main() asserts both.
# The headline is one language per source, its lines as they break on the card.
SOURCES = [
    ("BR", "brighton", ["Сыграем", "в дурака?"]),   # Brighton Beach: Russian only
    ("WS", "wsp", ["Play", "Durak?"]),              # Washington Square Park: English only
]
# Payload forms. www is the lobby QR's form (foolish/src/components/Lobby.tsx); Alex's
# phone opened WWW.FOOLISH.CARDS/BR as a link, while the bare FOOLISH.CARDS/BR opened a
# web search.
PAYLOAD_FORMS = {
    "www": "WWW.FOOLISH.CARDS/",
    "https": "HTTPS://FOOLISH.CARDS/",
}
PAYLOAD_FORM = "www"
# The QR version each (form, error correction) must come out as, asserted per face.
QR_VERSIONS = {
    ("www", "m"): 1, ("www", "q"): 2, ("www", "h"): 2,
    ("https", "m"): 2, ("https", "q"): 2, ("https", "h"): 3,
}
EC_LEVELS = ["m", "h"]  # the sets generated by default, each into out/<EC>/
PRINTED_URL = "foolish.cards"
# ---------------------------------------------------------------------------------------

GAME_ID_ALPHABET = "0123456789abcdef"
GAME_ID_LEN = 6

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)  # foolish/
OUT = os.path.join(HERE, "out")
FERN_C = os.path.join(HERE, "fern.c")
OSWALD = os.path.join(HERE, "fonts", "Oswald.ttf")  # the preview sheet's captions only
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"

# MPC "Traditional Poker sized card (2.5" x 3.5")" template, poker-size.pdf from
# https://www.makeplayingcards.com/pops/pc-temp-guide.html :
#   full bleed 2.74 x 3.74 in = 822 x 1122 px, cut 750 x 1050 px, safe 690 x 990 px, 300 dpi.
DPI = 300
W, H = 822, 1122
TRIM = (36, 36, 786, 1086)   # cut line, 36 px bleed each side
SAFE = (66, 66, 756, 1056)   # 30 px inside the cut line
CX = W // 2

INK = (12, 10, 10)
QR_INK = (0, 0, 0)           # CardFace.tsx's black-suit ink, on its #ffffff face
FACE = (255, 255, 255)       # --color-card-face, default theme

SRGB = ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB")).tobytes()

SS = 3  # supersampling for the back's frame


def font(path, size, weight=None):
    f = ImageFont.truetype(path, size)
    if weight:
        f.set_variation_by_name(weight)
    return f


# ---- the back ---------------------------------------------------------------------------
# The app's card back is generated, not drawn: the IFS fern of fernFractal.tsx (gold
# spine, red and bronze bulbs, on black, under a thin dark-red frame in CardBack.tsx).
# fern.c is a port of it; build_fern() proves the port against the e2e test's digest of
# the real code before anything is rendered.

# foolish/e2e/fern_texture.test.ts: the title fern (1400 x 1960, 12M points, 2 px dots,
# scaleY 14 * 1400/70), off the seeded LCG, through the no-WebGL path (points computed
# twice), must paint exactly these pixels after exactly this many random draws.
WEB_DIGEST = "9c51cfc05121234948dfa83cf87b3214182c840c79583bacb02eda44cf8c07b6"
WEB_DRAWS = "50884422"

# FernCardBack.swift's look, the owner's round-7 pick: 1 px dots, 14 per pixel, alpha 0.20.
FERN_DENSITY = 14
FERN_ALPHA = 0.20
# CardBack.tsx (default theme, StyleContext cardBack): a 1 px #8B0000 border with a 5 px
# radius on a 50 px card, border-box. At print scale (750 / 50 = 15) that is a 15 px band
# whose outer edge is the cut line with a 75 px radius, so its inner edge is 15 px inside
# the cut with a 60 px radius. The fern shows inside the inner edge. Outside it the band
# runs on through the bleed to the image edge, so a cut that drifts (MPC: about 1/16 in)
# shows more or less red, never black.
FRAME = (139, 0, 0)
GAME_SCALE = (TRIM[2] - TRIM[0]) / 50   # 15: print px per game CSS px
FRAME_PX = round(1 * GAME_SCALE)
FRAME_INNER_RADIUS = round(5 * GAME_SCALE) - FRAME_PX


def build_fern(tmp):
    exe = os.path.join(tmp, "fern")
    subprocess.run(["cc", "-O2", "-ffp-contract=off", "-o", exe, FERN_C, "-lm"], check=True)
    out = os.path.join(tmp, "title.rgba")
    draws = subprocess.run([exe, "web", "1400", "1960", "12000000", "2", "280", "1", "2", out],
                           check=True, capture_output=True, text=True).stdout.strip()
    digest = hashlib.sha256(open(out, "rb").read()).hexdigest()
    ok = draws == WEB_DRAWS and digest == WEB_DIGEST
    print(f"{'OK  ' if ok else 'FAIL'} fern.c vs fern_texture.test.ts: draws {draws}, pixels {digest[:16]}")
    assert ok, "fern.c no longer draws the app's fern"
    return exe


def make_back(exe, tmp, frame=True):
    """The fern rendered natively at the print size, framed to the cut size exactly as
    the app frames it to the card (scale 14 * cut width / 70, centred), in the game's frame."""
    out = os.path.join(tmp, "back.rgba")
    scale = 14 * (TRIM[2] - TRIM[0]) / 70
    subprocess.run([exe, "ios", str(W), str(H), str(W * H * FERN_DENSITY), "1", str(FERN_ALPHA),
                    str(scale), str(W / 2), str(H / 2), out], check=True)
    img = Image.frombytes("RGBA", (W, H), open(out, "rb").read()).convert("RGB")
    if not frame:
        return img
    # the inner edge, antialiased: a supersampled mask of the rounded rectangle the fern shows through
    m = Image.new("L", (W * SS, H * SS), 0)
    x0, y0, x1, y1 = (v * SS for v in TRIM)
    inset = FRAME_PX * SS
    ImageDraw.Draw(m).rounded_rectangle([x0 + inset, y0 + inset, x1 - inset - 1, y1 - inset - 1],
                                        radius=FRAME_INNER_RADIUS * SS, fill=255)
    m = m.resize((W, H), Image.LANCZOS)
    return Image.composite(img, Image.new("RGB", (W, H), FRAME), m)


# ---- the faces -----------------------------------------------------------------------------
# The game's default-theme card face, foolish/src/components/GameDisplay/CardFace.tsx, is a
# 50 x 70 px border-box card (2 px border, 5 px radius), Georgia bold, red ink #dc2626,
# 20 px rank and 14 px suit glyph stacked in a 12 px wide index (line-height 15 px) 4 px in
# from the top-left, the same index rotated 180 degrees bottom-right, and a 32 px suit glyph
# centred. The rank label and suit glyph are the kernel's (foolish/c/cardtext/card_text.h:
# "A", "6", U+2665). FACE_HTML is that markup with those styles, laid out at CSS zoom 15
# (750 / 50, the cut width) by headless Chrome, so the fonts are real fonts at print size.
# Kept: everything above, except the centre suit, which the QR replaces, and the 2 px
# black border, which stays as a transparent border so nothing moves: a 30 px black line
# on the cut would show every bit of MPC's cut drift.
# Added: the headline (top right) and the printed URL (bottom left), in the face's own
# Georgia bold, in the two corners the indices leave free.

FACE_HTML = """<!doctype html><html><head><meta charset="utf-8"><style>
html, body {{ margin: 0; width: {W}px; height: {H}px; overflow: hidden; background: #ffffff; }}
* {{ box-sizing: border-box; }}
.card {{ position: absolute; left: {left}px; top: {top}px; zoom: {zoom};
  background-color: #ffffff; width: 50px; height: 70px; border-radius: 5px;
  border: 2px solid transparent; font-family: Georgia, serif; font-weight: bold;
  color: #dc2626; display: flex; flex-direction: column; font-size: 20px; line-height: 15px; }}
.ix {{ width: 12px; position: absolute; font-size: 20px; display: flex; flex-direction: column;
  align-items: center; justify-content: center; text-align: center; }}
.head {{ position: absolute; right: 4px; top: 5px; text-align: right; font-size: 4.6px;
  line-height: 5.4px; color: #dc2626; }}
.url {{ position: absolute; left: 4px; bottom: 5px; font-size: 3.8px; line-height: 4.4px; color: #000000; }}
</style></head><body><div class="card">
  <div class="ix" style="left: 4px; top: 4px;"><div>{rank}</div><div><span style="font-size: 14px">{suit}</span></div></div>
  <div class="ix" style="bottom: 4px; right: 4px; transform: rotate(180deg);"><div>{rank}</div><div><span style="font-size: 14px">{suit}</span></div></div>
  <div class="head">{head}</div>
  <div class="url">{url}</div>
</div></body></html>
"""
SUIT_HEARTS = "\u2665"


def chrome_face(rank, head_lines, tmp, name):
    """The face's layer (everything but the QR) as Chrome draws it, 822 x 1122."""
    page = os.path.join(tmp, name + ".html")
    shot = os.path.join(tmp, name + ".png")
    with open(page, "w", encoding="utf-8") as f:
        f.write(FACE_HTML.format(W=W, H=H, left=TRIM[0] / GAME_SCALE, top=TRIM[1] / GAME_SCALE, zoom=GAME_SCALE,
                                 rank=html.escape(rank), suit=SUIT_HEARTS,
                                 head="<br>".join(html.escape(l) for l in head_lines), url=html.escape(PRINTED_URL)))
    subprocess.run(["nice", "-n", "10", CHROME, "--headless=new", "--disable-gpu", "--no-first-run",
                    "--no-default-browser-check", f"--user-data-dir={os.path.join(tmp, 'chrome')}",
                    "--hide-scrollbars", "--force-device-scale-factor=1", f"--window-size={W},{H}",
                    f"--screenshot={shot}", "file://" + page],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    img = Image.open(shot).convert("RGB")
    assert img.size == (W, H), img.size
    return img


def qr_symbol(payload, error, version):
    q = segno.make(payload, error=error, boost_error=False, micro=False)
    assert q.mode == "alphanumeric", (payload, q.mode)
    assert q.version == version, f"{payload}: version {q.version}, want {version}"
    return q


def draw_qr(layer, q, module):
    """Dark modules only, pixel exact, centred where the game's centre suit sits. The
    quiet zone is the card itself, and it must be: assert nothing else is drawn there."""
    img = layer.copy()
    n = q.symbol_size(border=4)[0]
    x0, y0 = (TRIM[0] + TRIM[2] - n * module) // 2, (TRIM[1] + TRIM[3] - n * module) // 2
    clear = np.asarray(img.crop((x0, y0, x0 + n * module, y0 + n * module)))
    assert (clear == FACE).all(), "the QR and its quiet zone must sit on bare card"
    d = ImageDraw.Draw(img)
    for r, row in enumerate(q.matrix_iter(border=4)):
        for c, dark in enumerate(row):
            if dark:
                d.rectangle([x0 + c * module, y0 + r * module,
                             x0 + (c + 1) * module - 1, y0 + (r + 1) * module - 1], fill=QR_INK)
    return img


# The QR's module size per version: as big as the gap between the two indices' hearts allows.
MODULE = {1: 9, 2: 8}

LAYOUTS = {
    "A": ("ace", "A"),   # the ace of hearts, its one pip the QR
    "B": ("six", "6"),   # the six of hearts, the lowest card of the 36-card Durak deck
}


# ---- preview sheet and checks -------------------------------------------------------------

def guides(img):
    """The card with its cut line (solid) and safe line (dashed) drawn on."""
    g = img.copy()
    d = ImageDraw.Draw(g)
    d.rectangle(TRIM, outline=(0, 160, 255), width=2)
    x0, y0, x1, y1 = SAFE
    dash = 12
    for x in range(x0, x1, dash * 2):
        d.line([(x, y0), (min(x + dash, x1), y0)], fill=(230, 0, 160), width=2)
        d.line([(x, y1), (min(x + dash, x1), y1)], fill=(230, 0, 160), width=2)
    for y in range(y0, y1, dash * 2):
        d.line([(x0, y), (x0, min(y + dash, y1))], fill=(230, 0, 160), width=2)
        d.line([(x1, y), (x1, min(y + dash, y1))], fill=(230, 0, 160), width=2)
    return g


def preview(back, face, title):
    gap, margin, head = 90, 60, 110
    sheet = Image.new("RGB", (2 * W + gap + 2 * margin, H + head + 2 * margin + 60), (235, 235, 235))
    d = ImageDraw.Draw(sheet)
    f = font(OSWALD, 34, "Medium")
    small = font(OSWALD, 24, "Regular")
    d.text((margin, margin - 10), title, font=f, fill=INK)
    d.text((margin, margin + 40),
           "Actual size at 300 dpi (print at 100%). Blue solid: cut line 2.5 x 3.5 in. "
           "Pink dashed: safe area. Outer edge: bleed 2.74 x 3.74 in.", font=small, fill=(60, 60, 60))
    y = margin + head
    sheet.paste(guides(back), (margin, y))
    sheet.paste(guides(face), (margin + W + gap, y))
    d.text((margin, y + H + 12), "BACK", font=small, fill=INK)
    d.text((margin + W + gap, y + H + 12), "FACE", font=small, fill=INK)
    return sheet


def decode(img):
    det = cv2.QRCodeDetector()
    a = cv2.cvtColor(np.asarray(img.convert("RGB")), cv2.COLOR_RGB2BGR)
    text, _, _ = det.detectAndDecode(a)
    return text


SURE_SCALE = 0.6  # from 60% of print size up, every size must read


def shrink_sweep(img, payload):
    """Decode the face shrunk to every even width from 160 px to full size, as a phone
    further and further away sees it. Returns (share that read, the smallest width from
    which every larger one reads). OpenCV's detector misses some sizes at random once a
    module is a few pixels, so the share, not one size, is the measure."""
    widths = range(160, W + 1, 2)
    read = [decode(img.resize((w, round(w * H / W)), Image.LANCZOS)) == payload for w in widths]
    sure = W
    for w, ok in zip(reversed(widths), reversed(read)):
        if not ok:
            break
        sure = w
    return sum(read) / len(read), sure


def qr_contrast(img, q, module):
    """Symbol contrast as ISO 18004 grades it, (light - dark) reflectance over the symbol and
    its quiet zone, taken from the saved file at each module's centre (1.0 is black on white)."""
    g = np.asarray(img.convert("L")).astype(float) / 255
    n = q.symbol_size(border=4)[0]
    x0, y0 = (TRIM[0] + TRIM[2] - n * module) // 2, (TRIM[1] + TRIM[3] - n * module) // 2
    dark, light = [], []
    for r, row in enumerate(q.matrix_iter(border=4)):
        for c, on in enumerate(row):
            v = g[y0 + r * module + module // 2, x0 + c * module + module // 2]
            (dark if on else light).append(v)
    return min(light) - max(dark)


def check_short_path(code):
    assert len(code) != GAME_ID_LEN, f"{code}: a short path must not be {GAME_ID_LEN} long (a game id's length)"
    assert any(c.lower() not in GAME_ID_ALPHABET for c in code), \
        f"{code}: needs a character outside the game-id alphabet {GAME_ID_ALPHABET}"
    assert code == code.upper(), f"{code}: upper-case keeps the QR alphanumeric"


def save_print(img, path):
    """What MPC's uploader takes: an 8-bit RGB PNG, sRGB profile embedded, 300 dpi, 822 x 1122."""
    img.convert("RGB").save(path, dpi=(DPI, DPI), icc_profile=SRGB)
    back = Image.open(path)
    assert back.format == "PNG" and back.mode == "RGB" and back.size == (W, H), (path, back.mode, back.size)
    assert tuple(round(v) for v in back.info["dpi"]) == (DPI, DPI), back.info.get("dpi")
    assert back.info.get("icc_profile") == SRGB


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--layout", default="all", choices=["all"] + sorted(LAYOUTS))
    ap.add_argument("--payload", default=PAYLOAD_FORM, choices=sorted(PAYLOAD_FORMS))
    ap.add_argument("--ec", default="all", type=str.lower, choices=["all", "m", "q", "h"],
                    help="error correction; each level goes to out/<EC>/ (default: " + " and ".join(EC_LEVELS) + ")")
    ap.add_argument("--no-frame", action="store_true", help="the back without CardBack.tsx's #8B0000 frame")
    args = ap.parse_args()
    layouts = sorted(LAYOUTS) if args.layout == "all" else [args.layout]
    prefix = PAYLOAD_FORMS[args.payload]
    levels = EC_LEVELS if args.ec == "all" else [args.ec]

    assert os.path.exists(CHROME), "the faces are drawn by Google Chrome, headless"
    with tempfile.TemporaryDirectory() as tmp:
        back = make_back(build_fern(tmp), tmp, not args.no_frame)
        layers = {(code, key): chrome_face(rank, head, tmp, f"{key}_{code}")
                  for code, _, head in SOURCES for key, (_, rank) in LAYOUTS.items() if key in layouts}
    assert back.size == (W, H)

    failures = 0
    for error in levels:
        version = QR_VERSIONS[(args.payload, error)]
        out = os.path.join(OUT, error.upper())
        os.makedirs(out, exist_ok=True)
        save_print(back, os.path.join(out, "back.png"))
        print(f"{error.upper()}/back.png  {W}x{H}")
        for code, name, _ in SOURCES:
            check_short_path(code)
            payload = prefix + code
            q = qr_symbol(payload, error, version)
            for key in layouts:
                label, _ = LAYOUTS[key]
                face = draw_qr(layers[(code, key)], q, MODULE[q.version])
                path = os.path.join(out, f"face_{key}_{label}_{code}.png")
                save_print(face, path)
                # decode the saved file at full size, then shrunk step by step
                saved = Image.open(path)
                full = decode(saved)
                share, sure = shrink_sweep(saved, payload)
                contrast = qr_contrast(saved, q, MODULE[q.version])
                ok = full == payload and sure <= SURE_SCALE * W and contrast >= 0.9
                failures += not ok
                print(f"{'OK  ' if ok else 'FAIL'} {error.upper()}/{os.path.basename(path):24s} {name:9s} "
                      f"QR v{q.version}-{error.upper()} {MODULE[q.version]}px want {payload!r} full={full!r} "
                      f"shrunk: {share:.0%} of sizes read, every size from {sure / W:.0%} up; contrast={contrast:.2f}")
                preview(back, face, f"Foolish promo card, layout {key} ({label}), source {code}, QR v{q.version}-{error.upper()}") \
                    .save(os.path.join(out, f"preview_{key}_{label}_{code}.png"), dpi=(DPI, DPI))
    if failures:
        print(f"{failures} QR check(s) failed")
        sys.exit(1)
    print("all QR checks passed")


if __name__ == "__main__":
    main()
